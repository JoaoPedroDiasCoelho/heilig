CREATE TABLE IF NOT EXISTS public.product_images (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id integer NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
  image_url text NOT NULL,
  public_id text,
  is_featured boolean NOT NULL DEFAULT false,
  sort_order integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT product_images_product_url_unique UNIQUE (product_id, image_url)
);

CREATE UNIQUE INDEX IF NOT EXISTS product_images_one_featured_per_product_idx
  ON public.product_images (product_id)
  WHERE is_featured = true;

CREATE UNIQUE INDEX IF NOT EXISTS product_images_cloudinary_public_id_idx
  ON public.product_images (public_id)
  WHERE public_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS product_images_product_order_idx
  ON public.product_images (product_id, sort_order, id);

UPDATE public.product_images AS image
SET is_featured = false
FROM public.products AS product
WHERE image.product_id = product.id
  AND image.is_featured = true
  AND image.image_url <> product.image;

INSERT INTO public.product_images (product_id, image_url, is_featured, sort_order)
SELECT id, image, true, 0
FROM public.products
WHERE image <> ''
ON CONFLICT (product_id, image_url) DO UPDATE
SET is_featured = true;
